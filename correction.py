
import requests

OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL = "qwen2.5:7b"


def correct_text(text):

    prompt = f"""
Ты редактор казахского языка.

Исправь ошибки автоматического распознавания речи
в разговоре клиента и менеджера магазина красок.

Правила:
- Исправляй только ошибки распознавания и грамматики.
- Сохраняй исходный смысл.
- Не добавляй новые предложения и факты.
- Не придумывай суммы, цены и сроки.
- Если слово или число нельзя уверенно восстановить,
  напиши [тексеру қажет].
- Не переводи текст на русский язык.
- Верни только исправленный казахский текст.

Исходный текст:
{text}
"""

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0,
                "num_ctx": 4096
            }
        },
        timeout=300
    )

    response.raise_for_status()

    return response.json()["response"].strip()


if __name__ == "__main__":

    text = """
    Сәлеметисіп, маға құнақ бөлмеге арналған
    жуылатын бояу керек. Бүйшетім, илумың, теңге.
    Сәлеметисіп, сізген сәйкес келетін бояулары
    түсінін. Бүгін сағат 5 кедейін жүйбіремін.
    Жақсы, жауығыңызды кітемін.
    """

    print("Мәтін түзетілуде...")
    print(correct_text(text))
